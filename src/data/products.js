export function getProduct(slug) {
  return products.find((p) => p.slug === slug)
}

export function getByCategory(category) {
  return products.filter((p) => p.category === category)
}

export function featuredServices() {
  return products.filter((p) => p.featured === 'service')
}

export function featuredProducts() {
  return products.filter((p) => p.featured === 'product')
}

export function relatedProducts(product) {
  const fromSlugs = (product.relatedSlugs || []).map(getProduct).filter(Boolean)
  if (fromSlugs.length) return fromSlugs
  return products.filter((p) => p.category === product.category && p.slug !== product.slug).slice(0, 3)
}

export function searchProducts(q) {
  const s = q.trim().toLowerCase()
  if (!s) return []
  return products.filter((p) => p.title.toLowerCase().includes(s) || p.excerpt.toLowerCase().includes(s))
}
